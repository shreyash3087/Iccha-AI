import type { BusinessProfile, ProductItem, TemplateId } from "@/types/business";

export interface TemplateProps {
  profile: BusinessProfile;
  cart: Record<string, number>;
  onAddToCart: (item: ProductItem) => void;
  onRemoveFromCart: (item: ProductItem) => void;
  onOpenQR: () => void;
}

export function getWhatsAppHref(phone?: string | null, message?: string): string {
  if (!phone) return "#";
  const clean = phone.replace(/\D/g, "");
  const num = clean.startsWith("91") ? clean : `91${clean}`;
  return `https://wa.me/${num}${message ? `?text=${encodeURIComponent(message)}` : ""}`;
}

export function getGoogleReviewUrl(profile: BusinessProfile): string {
  if (profile.places_id) {
    return `https://search.google.com/local/writereview?placeid=${profile.places_id}`;
  }
  const q = encodeURIComponent(`${profile.shop_name} ${profile.locality || ""} ${profile.city || ""}`);
  return `https://www.google.com/maps/search/?api=1&query=${q}`;
}

export function buildWhatsAppCartMessage(
  profile: BusinessProfile,
  cart: Record<string, number>
): string {
  const items = profile.products || [];
  const lines: string[] = [];

  lines.push(`*${profile.shop_name}* से ऑर्डर`);
  lines.push("─────────────────");

  for (const [name, qty] of Object.entries(cart)) {
    if (qty <= 0) continue;
    const item = items.find((i) => i.name === name);
    const priceStr = item?.price ? ` — ₹${(item.price * qty).toLocaleString("en-IN")}` : "";
    lines.push(`• ${name} × ${qty}${priceStr}`);
  }

  const total = Object.entries(cart).reduce((sum, [name, qty]) => {
    const it = items.find((i) => i.name === name);
    return sum + (it?.price || 0) * qty;
  }, 0);

  if (total > 0) {
    lines.push("─────────────────");
    lines.push(`*कुल: ₹${total.toLocaleString("en-IN")}*`);
  }

  lines.push("");
  lines.push("कृपया confirm करें और delivery address बताएं।");
  return lines.join("\n");
}

export function resolveTemplate(profile: BusinessProfile): TemplateId {
  if (profile.template_id) return profile.template_id as TemplateId;

  const cat = profile.category || "product";
  // default template per category
  if (cat === "service") return "service-elegant";
  if (cat === "other") return "other-simple";
  return "product-classic";
}

